#!/usr/bin/env node
/* Writes browser copies of JSON data, because index.html must work from file:// (no fetch). */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const wrap = (key, obj) => `/* GENERATED by scripts/build-browser-data.js from JSON. SYNTHETIC data, do not edit by hand. */\n(function (root, data) { if (typeof module === "object" && module.exports) module.exports = data; root.QT = root.QT || {}; root.QT.${key} = data; })(typeof globalThis !== "undefined" ? globalThis : this, ${JSON.stringify(obj)});\n`;
const out = [['data/blind/requests.json', 'data/blind/requests.js', 'blind'], ['eval/kpi.json', 'eval/kpi-data.js', 'kpi'], ['eval/blind-results.json', 'eval/blind-results.js', 'blindResults']];
for (const [src, dst, key] of out) {
  fs.writeFileSync(path.join(root, dst), wrap(key, JSON.parse(fs.readFileSync(path.join(root, src), 'utf8'))));
  console.log('wrote', dst);
}
