/* Renders eval/KPI.md from the output of eval/kpi.js. */
'use strict';
const stats = require('./stats.js');
module.exports = function report(k) {
  const f = stats.fmt, p = stats.pct1, r1 = v => (Math.round(v * 10) / 10).toFixed(1), r0 = v => String(Math.round(v));
  const o = [];
  const M = k.model;
  o.push('# KPIs: what the tool changes, on SYNTHETIC data');
  o.push('');
  o.push('> **All data is SYNTHETIC** (161 generated requests plus the 60-request blind holdout). No real lead is in these numbers. Generated by `node eval/kpi.js --write`.');
  o.push('');
  o.push('Each number is labelled with how it was obtained: **MEASURED** (computed from the rules and the labels), **MODELED** (reviewer time from a keystroke-level model; no person was timed), or **SIMULATED** (arrival times replayed against a modeled reviewer).');
  o.push('');
  o.push('## The manual baseline');
  o.push('');
  o.push('A person opens each request **in arrival order**, applies the same written rules **without error** (the labels are exactly what a careful reader decides), and sends the right reply from a **saved template**. A weaker baseline types each reply **from scratch**. Both have the same reviewer, available at the same times as the tool\'s reviewer.');
  o.push('');
  o.push('Why this baseline: it is how a small team handles leads today (read the email, decide, reply), and it is a strong one. Templates and a perfect reader make the comparison harder for the tool, not easier. Because the manual reader is assumed perfect, the tool cannot beat it on accuracy. It has to win on time, and it must not hand the reviewer a harmful suggestion.');
  o.push('');
  o.push('## 1. Time to a triage decision (MEASURED)');
  o.push('');
  o.push(`The rules produce a suggested action, reasons and a draft in **${k.computeMsPerRequest.toFixed(2)} ms per request** in Node on this machine. By hand, there is no decision until a person opens the request, so triage and approval happen together (section 3).`);
  o.push('');
  o.push('## 2. Reviewer pace (MODELED)');
  o.push('');
  o.push('Seconds per request: reading time plus keystroke-level operators, and the cost of fixing a wrong suggestion before approving. Approvals per minute = 60 / mean seconds, with a 95% bootstrap interval over requests.');
  o.push('');
  o.push('| Requests | Tool | Manual, templates | Manual, from scratch |');
  o.push('| --- | --- | --- | --- |');
  for (const [set, label] of [['synthetic', '161 synthetic (tool 97% right)'], ['blind', '60 blind (tool 53% right)']]) {
    const P = k.pace[set];
    const c = x => `**${r1(x.perMin)}/min** (${r1(x.perMinLo)}–${r1(x.perMinHi)}) · ${r0(x.secPerRequest)} s each · ${r0(x.minutesPer100)} min per 100`;
    o.push(`| ${label} | ${c(P.tool)} | ${c(P.template)} | ${c(P.scratch)} |`);
  }
  o.push('');
  o.push(`Model constants: keystroke ${M.K} s, point ${M.P} s, click ${M.B} s, mental step ${M.M} s (Card, Moran & Newell 1980); reading ${M.readWpm} wpm (Brysbaert 2019). **Assumed, not sourced:** composing from scratch at ${M.composeWpm} wpm; a ${M.lookupSec} s county lookup when only a ZIP is given; ${M.fixTypedWords} words retyped to fix a wrong ask list. The tool reviewer reads the whole card, reasons and draft included, and catches every wrong suggestion. A reviewer who rubber-stamps would be faster and would send the wrong reply.`);
  o.push('');
  o.push('## 3. Leads with a person-approved next step within 1 hour (SIMULATED)');
  o.push('');
  o.push(`The reviewer checks the queue every C minutes between ${M.windowStart / 60}am and ${M.windowEnd / 60 - 12}pm, works until it is empty, and stops at ${M.windowEnd / 60 - 12}pm. The 1-hour clock starts at arrival, or at ${M.windowStart / 60}am for requests that arrive overnight. The tool works the queue urgent-first, then by score, screen-outs last; the manual reader works in arrival order. Leads only (spam, repeats and not-a-fit are excluded from the share but still take the reviewer\'s time).`);
  o.push('');
  for (const [name, s] of Object.entries(k.sims)) {
    o.push(`**${name}**: ${s.note}.`);
    o.push('');
    o.push('| Check every | Tool | Manual, templates | Manual, from scratch | Reviewer hours (tool / templates / scratch) |');
    o.push('| --- | --- | --- | --- | --- |');
    for (const [C, c] of Object.entries(s.byCadence)) {
      const cell = x => `${f(x.within1h)} · median ${r0(x.medianMin)} min`;
      o.push(`| ${C} min | ${cell(c.tool)} | ${cell(c.template)} | ${cell(c.scratch)} | ${r1(c.tool.reviewerHours)} / ${r1(c.template.reviewerHours)} / ${r1(c.scratch.reviewerHours)} |`);
    }
    const u = s.byCadence[60];
    if (u.tool.urgentWithin1h) o.push(`| urgent leads only, 60 min | ${f(u.tool.urgentWithin1h)} | ${f(u.template.urgentWithin1h)} | ${f(u.scratch.urgentWithin1h)} | |`);
    o.push('');
  }
  const cur = k.sims['Current pace'].byCadence[60];
  o.push(`**What this says.** With checks every 30 or 60 minutes, the three methods land within a few leads of each other at every volume tested, up to all 161 requests in a single day. One reviewer clears each hour\'s arrivals well inside the hour, even typing from scratch, so triage speed is not what limits response time. (At 120-minute checks and very high volume, typing from scratch looks *better*. That is an artifact of the model: a slower reviewer is still at the desk when new leads arrive. It reflects time at the desk, not any benefit of typing slowly.) Two things do limit it. **How often someone checks:** about ${p(k.sims['Current pace'].byCadence[30].tool.within1h.p)} of leads within an hour when the queue is checked every 30 minutes, ${p(cur.tool.within1h.p)} at 60, ${p(k.sims['Current pace'].byCadence[120].tool.within1h.p)} at 120. **The end of the day:** at 60-minute checks, ${cur.tool.missedAfterLastCheck} of the tool\'s ${cur.tool.missed} late leads arrived after the last check of the day and waited until 8am. A last check at 7:55pm, or a phone alert for new leads, moves this KPI; faster triage does not.`);
  o.push('');
  o.push('Every lead in every scenario gets an approved next step within 24 hours, QBC\'s written promise, under all three methods.');
  o.push('');
  o.push('## 4. Harmful misses and false screen-outs (MEASURED, 95% Wilson intervals)');
  o.push('');
  o.push('A **harmful miss** is a suggestion that, approved as proposed, drops a real lead or makes the wrong promise (an in-area customer told to measure their own kitchen, a measure offered outside the area). A **false screen-out** is a real lead suggested as spam, not-a-fit or a duplicate. The manual baseline is assumed to make neither.');
  o.push('');
  o.push('| Set | Lane matches label | Harmful misses | False screen-outs (of real leads) |');
  o.push('| --- | --- | --- | --- |');
  const R = k.rates;
  o.push(`| 161 synthetic, v2 | ${f(R.synthetic.v2.lane)} | ${f(R.synthetic.v2.harmful)} | ${f(R.synthetic.v2.falseScreen)} |`);
  o.push(`| 161 synthetic, v1 (Nov 13) | ${f(R.synthetic.v1.lane)} | ${f(R.synthetic.v1.harmful)} | ${f(R.synthetic.v1.falseScreen)} |`);
  o.push(`| 60 blind, v2 | ${f(R.blind.v2.lane)} | ${f(R.blind.v2.harmful)} | ${f(R.blind.v2.falseScreen)} |`);
  o.push(`| 60 blind, v1 | ${f(R.blind.v1.lane)} | ${f(R.blind.v1.harmful)} | ${f(R.blind.v1.falseScreen)} |`);
  o.push(`| All 221, v2 | ${f(R.combined.v2.lane)} | ${f(R.combined.v2.harmful)} | ${f(R.combined.v2.falseScreen)} |`);
  o.push('');
  o.push('Zero observed is not zero. With 221 requests and no harmful miss, the 95% upper bound is the number in the last row.');
  o.push('');
  return o.join('\n') + '\n';
};
