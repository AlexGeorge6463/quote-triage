#!/usr/bin/env node
/* Runs the rules on the 60-request BLIND holdout (data/blind/requests.json) and records the result.
 * The holdout was written to docs/BLIND-SPEC.md and committed before this ran. It is run once:
 * the rules are not tuned on it. If a later change to the rules moves these numbers, test/blind.test.js
 * fails on purpose, because the recorded result no longer describes the rules. Write a new blind set then.
 *   node eval/blind.js           print the result
 *   node eval/blind.js --write   write eval/BLIND.md and eval/blind-results.json (done once, Nov 16)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const blind = require('../data/blind/requests.json');
const metrics = require('./metrics.js');
const stats = require('./stats.js');
const triage = require('../src/triage.js');
const baseline = require('./baseline-v1.js');

const SCREEN = ['spam', 'decline', 'duplicate'];
function summarize(m, reqs, preds) {
  const byId = new Map(preds.map(p => [p.id, p]));
  const leads = reqs.filter(r => metrics.LEADS.includes(r.label.lane));
  const falseScreen = leads.filter(r => SCREEN.includes(byId.get(r.id).lane)).length;
  return {
    lane: stats.wilson(m.laneOk, m.n), harmful: stats.wilson(m.harmful, m.n), falseScreen: stats.wilson(falseScreen, leads.length),
    leads: stats.wilson(m.leadOk, m.leadsN), full: stats.wilson(m.fullOk, m.n), ask: m.ask, urgent: m.urgent, dup: m.dup,
    categories: m.categories, confusion: m.confusion, misses: m.misses
  };
}
function run() {
  const reqs = blind.requests;
  const v2p = triage.runAll(reqs);
  const v1p = baseline.runAll(reqs);
  return {
    v2: summarize(metrics.score(reqs, v2p), reqs, v2p),
    v1: summarize(metrics.score(reqs, v1p), reqs, v1p),
    leadIds: reqs.filter(r => metrics.LEADS.includes(r.label.lane)).length
  };
}
module.exports = { run };

if (require.main === module) {
  const r = run();
  const f = stats.fmt;
  console.log(`BLIND holdout, ${blind.requests.length} SYNTHETIC requests`);
  for (const k of ['v2', 'v1']) {
    const s = r[k];
    console.log(`${k}: lane ${f(s.lane)} · harmful ${f(s.harmful)} · false screen-out ${f(s.falseScreen)}`);
  }
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(__dirname, 'blind-results.json'), JSON.stringify({ synthetic: true, ranOnce: '2026-11-16', n: blind.requests.length, v2: r.v2, v1: r.v1 }, null, 1) + '\n');
    fs.writeFileSync(path.join(__dirname, 'BLIND.md'), report(r));
    console.log('wrote eval/BLIND.md and eval/blind-results.json');
  }
}

function report(r) {
  const L = metrics.LANE_LABEL, f = stats.fmt, p = stats.pct1;
  const v2 = r.v2, v1 = r.v1;
  const styles = ['clean', 'typos', 'spanish', 'voicemail', 'forwarded', 'minimal'];
  const out = [];
  out.push('# Blind holdout: 60 SYNTHETIC requests, run once');
  out.push('');
  out.push('> **All data is SYNTHETIC.** Hand-written to [`docs/BLIND-SPEC.md`](../docs/BLIND-SPEC.md). The spec was committed first, then the 60 requests, then this single run. Nothing in the rules was changed after seeing it. Generated by `node eval/blind.js --write`.');
  out.push('');
  out.push('**Not independent.** The author of the requests also wrote the rules. The spec and the order of commits limit the bias; they do not remove it.');
  out.push('');
  out.push('## Headline (95% Wilson intervals)');
  out.push('');
  out.push('| | v2 rules | v1 rules (reference) |');
  out.push('| --- | --- | --- |');
  out.push(`| Routed to the labeled action | ${f(v2.lane)} | ${f(v1.lane)} |`);
  out.push(`| Harmful misses (approving as proposed drops a lead or makes the wrong promise) | ${f(v2.harmful)} | ${f(v1.harmful)} |`);
  out.push(`| False screen-outs (a real lead sent to spam, not-a-fit or duplicate) | ${f(v2.falseScreen)} | ${f(v1.falseScreen)} |`);
  out.push(`| Real leads routed right | ${f(v2.leads)} | ${f(v1.leads)} |`);
  out.push(`| Fully right (lane, asks, urgency, merge target) | ${f(v2.full)} | ${f(v1.full)} |`);
  out.push(`| Draft asks for exactly what is missing | ${v2.ask.ok}/${v2.ask.n} | ${v1.ask.ok}/${v1.ask.n} |`);
  out.push(`| Urgent flag: precision / recall | ${v2.urgent.precision ?? '–'}% / ${v2.urgent.recall ?? '–'}% | – / 0% |`);
  out.push(`| Duplicates merged into the right request | ${v2.dup.ok}/${v2.dup.n} | ${v1.dup.ok}/${v1.dup.n} |`);
  out.push('');
  out.push('## By writing style');
  out.push('');
  out.push('| Style | Requests | v2 | v1 |');
  out.push('| --- | --- | --- | --- |');
  styles.forEach(s => out.push(`| ${s} | ${v2.categories[s].n} | ${v2.categories[s].ok}/${v2.categories[s].n} | ${v1.categories[s].ok}/${v1.categories[s].n} |`));
  out.push('');
  out.push('## Confusion matrix, v2');
  out.push('');
  out.push('| labeled ↓ / proposed → | ' + metrics.LANES.map(k => L[k]).join(' | ') + ' |');
  out.push('| --- | ' + metrics.LANES.map(() => '---:').join(' | ') + ' |');
  metrics.LANES.forEach(t => out.push(`| **${L[t]}** | ` + metrics.LANES.map(q => { const v = v2.confusion[t][q]; return v ? (t === q ? `**${v}**` : String(v)) : '·'; }).join(' | ') + ' |'));
  out.push('');
  out.push(`## Every v2 miss (${v2.misses.length})`);
  out.push('');
  out.push('| Request | Style | Miss | Severity |');
  out.push('| --- | --- | --- | --- |');
  const byId = new Map(blind.requests.map(q => [q.id, q]));
  v2.misses.forEach(m => out.push(`| ${m.id} | ${byId.get(m.id).category} | ${m.what} | ${m.harmful ? '**harmful**: ' : ''}${m.why} |`));
  out.push('');
  return out.join('\n') + '\n';
}
