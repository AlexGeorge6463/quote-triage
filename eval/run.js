#!/usr/bin/env node
/* Runs v1 and the current rules on the SYNTHETIC set and scores both against the labels.
 *   node eval/run.js          print a summary of every split
 *   node eval/run.js --dev    print the dev split only (used while fixing, so the holdout stays unseen)
 *   node eval/run.js --write  also write eval/results.json and eval/REPORT.md
 */
'use strict';
const fs = require('fs');
const path = require('path');
const data = require('../data/requests.js');
const metrics = require('./metrics.js');
const baseline = require('./baseline-v1.js');
let current = null;
try { current = require('../src/triage.js'); } catch (e) { if (e.code !== 'MODULE_NOT_FOUND') throw e; }

const args = new Set(process.argv.slice(2));
const devOnly = args.has('--dev');
const all = data.requests;
const reqs = devOnly ? all.filter(r => r.split === 'dev') : all;

function run(engine) {
  // Every engine sees the whole stream in time order (duplicate detection needs history), then is scored on the chosen split.
  const preds = engine.runAll(all, { now: data.clock });
  const ids = new Set(reqs.map(r => r.id));
  return metrics.score(reqs, preds.filter(p => ids.has(p.id)));
}

const before = run(baseline);
const after = current ? run(current) : null;
const line = (name, m) => `${name.padEnd(14)} lane ${m.laneOk}/${m.n} = ${m.lanePct}%  ·  leads ${m.leadPct}%  ·  fully right ${m.fullPct}%  ·  harmful misses ${m.harmful}  ·  asks ${m.ask.pct}%  ·  urgent P/R ${m.urgent.precision ?? '-'}/${m.urgent.recall ?? '-'}  ·  dups ${m.dup.pct}%`;
console.log(`${reqs.length} SYNTHETIC requests${devOnly ? ' (dev split only)' : ''}`);
console.log(line('v1 baseline', before));
if (after) console.log(line('current', after));
if (!devOnly) {
  for (const s of ['dev', 'holdout']) {
    const b = before.splits[s], a = after && after.splits[s];
    console.log(`  ${s.padEnd(8)} v1 ${b.ok}/${b.n} = ${b.pct}%${a ? `   current ${a.ok}/${a.n} = ${a.pct}%` : ''}`);
  }
}
if (devOnly && after) {
  console.log('\nCurrent misses (dev):');
  after.misses.forEach(m => console.log(`  ${m.id} [${m.category}] ${m.what}${m.harmful ? '  HARMFUL: ' + m.why : ''}`));
}

if (args.has('--write')) {
  const out = { generated: 'eval/run.js', synthetic: true, n: all.length, clock: data.clock, before, after };
  fs.writeFileSync(path.join(__dirname, 'results.json'), JSON.stringify(out, null, 1) + '\n');
  fs.writeFileSync(path.join(__dirname, 'REPORT.md'), report(before, after));
  console.log('\nwrote eval/results.json and eval/REPORT.md');
}

function report(b, a) {
  const L = metrics.LANE_LABEL;
  const cat = {};
  all.forEach(r => { cat[r.category] = (cat[r.category] || 0) + 1; });
  const hold = all.filter(r => r.split === 'holdout').length;
  const rows = [];
  const p = v => (v == null ? '–' : `${v}%`);
  rows.push(`# Evaluation report: Quote Triage on ${all.length} SYNTHETIC requests`);
  rows.push('');
  rows.push('> **All data is SYNTHETIC.** Every request was generated by `scripts/generate.js` (seed ' + data.seed + '). Names, phones (555-01xx) and emails (example domains) are invented. Cities and ZIP codes are real places, used only to test the service-area rule. No real QBC lead is in this set.');
  rows.push('');
  rows.push('Generated by `npm run eval` — do not edit by hand. The Evaluation tab in `index.html` computes the same numbers live in the browser.');
  rows.push('');
  rows.push('## Headline');
  rows.push('');
  rows.push('| | v1 (published Nov 13) | v2 (this branch) |');
  rows.push('| --- | --- | --- |');
  if (a) {
    rows.push(`| **Routed to the labeled action** (all ${b.n}) | ${b.laneOk}/${b.n} = **${p(b.lanePct)}** | ${a.laneOk}/${a.n} = **${p(a.lanePct)}** |`);
    rows.push(`| Same, dev split (${b.splits.dev.n}, used while fixing) | ${p(b.splits.dev.pct)} | ${p(a.splits.dev.pct)} |`);
    rows.push(`| Same, holdout split (${hold}, frozen before any fix) | ${p(b.splits.holdout.pct)} | ${p(a.splits.holdout.pct)} |`);
    rows.push(`| Real leads only (${b.leadsN}; the four lanes v1 had) | ${p(b.leadPct)} | ${p(a.leadPct)} |`);
    rows.push(`| Harmful misses (drop a lead or make the wrong promise) | ${b.harmful} | ${a.harmful} |`);
    rows.push(`| Draft asks for exactly what is missing (${b.ask.n} cases) | ${p(b.ask.pct)} | ${p(a.ask.pct)} |`);
    rows.push(`| Urgent flag, precision / recall (${b.urgent.tp + b.urgent.fn} urgent) | ${p(b.urgent.precision)} / ${p(b.urgent.recall)} | ${p(a.urgent.precision)} / ${p(a.urgent.recall)} |`);
    rows.push(`| Duplicates merged into the right request (${b.dup.n}) | ${p(b.dup.pct)} | ${p(a.dup.pct)} |`);
    rows.push(`| Fully right (lane, asks, urgency and merge target) | ${p(b.fullPct)} | ${p(a.fullPct)} |`);
  }
  rows.push('');
  rows.push('## By category');
  rows.push('');
  rows.push('| Category | Requests | v1 | v2 |');
  rows.push('| --- | --- | --- | --- |');
  Object.keys(cat).sort((x, y) => cat[y] - cat[x]).forEach(k => {
    rows.push(`| ${k} | ${cat[k]} | ${p(b.categories[k].pct)} | ${a ? p(a.categories[k].pct) : '–'} |`);
  });
  rows.push('');
  rows.push('v1\'s 100% on out-of-area is the flip side of its 0% on location formats: any location it could not read exactly (a ZIP, "winter park, fl", a neighborhood) fell through to Order-taking, which happens to be right for real out-of-area towns and harmful for everyone else. v2 reads those formats and asks for a ZIP when it cannot place a town, which costs it two held-out towns that are missing from the place table.');
  const matrix = (m, title) => {
    rows.push('');
    rows.push(`## Confusion matrix, ${title}`);
    rows.push('');
    rows.push('Rows are the labeled action, columns are what the rules proposed. The diagonal is correct.');
    rows.push('');
    rows.push('| labeled ↓ / proposed → | ' + metrics.LANES.map(k => L[k]).join(' | ') + ' |');
    rows.push('| --- | ' + metrics.LANES.map(() => '---:').join(' | ') + ' |');
    metrics.LANES.forEach(t => {
      rows.push(`| **${L[t]}** | ` + metrics.LANES.map(q => { const v = m.confusion[t][q]; return v ? (t === q ? `**${v}**` : String(v)) : '·'; }).join(' | ') + ' |');
    });
  };
  if (a) matrix(a, 'v2');
  matrix(b, 'v1');
  if (a) {
    rows.push('');
    rows.push(`## What v2 still gets wrong (${a.misses.length})`);
    rows.push('');
    rows.push('| Request | Split | Category | Miss | Severity |');
    rows.push('| --- | --- | --- | --- | --- |');
    a.misses.forEach(m => rows.push(`| ${m.id} | ${m.split} | ${m.category} | ${m.what} | ${m.harmful ? '**harmful**: ' : ''}${m.why} |`));
  }
  rows.push('');
  rows.push('## Method');
  rows.push('');
  rows.push(`- **${all.length} requests**: the 13 hand-made v1 requests, 9 new inbox requests written for the demo, and ${all.length - 22} generated across ${Object.keys(cat).length} categories (kitchen vs bath, size, timeline, out-of-area, spam, incomplete, duplicates, urgent, investors, remodelers, not-a-fit, and tricky negatives such as a real lead with a link or a prompt-injection line).`);
  rows.push('- **Labels come from policy, not code.** Each scenario in the generator states the action QBC\'s written routing rules require (settled Nov 11, 2026). The generator imports none of the triage code.');
  rows.push(`- **Holdout.** ${hold} generated requests use separate phrasing banks (different spam pitches, urgent wording, neighborhoods, towns) and were committed before any fix. While fixing, only the dev split was printed (\`npm run eval -- --dev\`).`);
  rows.push('- **v1 on raw forms.** v1 expected clean fields, so `eval/baseline-v1.js` maps each form the way a minimal form handler would (location as typed, `parseInt` on the units box, blank = missing). It cannot produce Spam, Duplicate or Not a fit, so those count against it; the "real leads only" row compares like with like.');
  rows.push('- **Harmful vs recoverable.** A miss is harmful if approving it as proposed would screen out a real lead, merge a new request away, tell an in-area customer to measure their own kitchen, or offer a measure outside the area. Everything else costs one extra question or is junk a person spots on review.');
  rows.push('');
  rows.push('## Limits');
  rows.push('');
  rows.push('- **Same author for data, labels and rules.** The generator, the labels and the fixes were written in one session by the same author (Claude, directed by Alex). The holdout guards against tuning to exact phrasings, but it is not a blind test. Treat the numbers as a regression suite for the written policy, not as real-world accuracy.');
  rows.push('- **Synthetic only.** No real request has been routed. Real intake will have phrasings this set does not.');
  rows.push('- **The place table is a sample.** Towns outside it are asked for a ZIP rather than guessed; a real deployment would load a full ZIP-to-county crosswalk.');
  rows.push('');
  return rows.join('\n');
}
